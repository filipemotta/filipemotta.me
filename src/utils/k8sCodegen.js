export function karpenterYaml(res, { clusterName, spotRatioPct, prefixDelegation = false }) {
  const cluster = safeName(clusterName);
  const inst = res.instance;
  const name = `general-${inst.family}`;
  const nodes = res.nodes.withSurge;
  const caps = capacityTypes(spotRatioPct);
  const capNote =
    caps.length === 2
      ? `        # Spot target ~${spotRatioPct}%. Karpenter prefers Spot when both are allowed;
        # to enforce a strict split, use two NodePools with separate limits.
`
      : "";

  return `# ${HEADER}
# ${inst.type}: ${res.pods.effective} effective pods/node, kubelet maxPods ${res.limit.limit}.
# Planned: ${res.nodes.steady} steady nodes, ${nodes} with surge across ${res.zones.length} AZs.
apiVersion: karpenter.sh/v1
kind: NodePool
metadata:
  name: ${name}
spec:
  template:
    spec:
      nodeClassRef:
        group: karpenter.k8s.aws
        kind: EC2NodeClass
        name: ${name}
      requirements:
        - key: node.kubernetes.io/instance-type
          operator: In
          values: ${list([inst.type])}
        - key: kubernetes.io/arch
          operator: In
          values: ${list([inst.arch])}
        - key: kubernetes.io/os
          operator: In
          values: ["linux"]
${capNote}        - key: karpenter.sh/capacity-type
          operator: In
          values: ${list(caps)}
        - key: topology.kubernetes.io/zone
          operator: In
          values: ${list(res.zones)}
      expireAfter: 720h
  limits:
    cpu: "${nodes * inst.vcpu}"
    memory: ${nodes * inst.ramGiB}Gi
  disruption:
    consolidationPolicy: WhenEmptyOrUnderutilized
    consolidateAfter: 1m
    budgets:
      - nodes: "10%"
---
apiVersion: karpenter.k8s.aws/v1
kind: EC2NodeClass
metadata:
  name: ${name}
spec:
  role: "KarpenterNodeRole-${cluster}"
  amiSelectorTerms:
    - alias: al2023@latest
  subnetSelectorTerms:
    - tags:
        karpenter.sh/discovery: "${cluster}"
  securityGroupSelectorTerms:
    - tags:
        karpenter.sh/discovery: "${cluster}"
  kubelet:
    # VPC CNI max ${res.limit.theoretical}${res.limit.capped ? `, capped at ${res.limit.cap}` : ""}.${
      prefixDelegation ? "\n    # Prefix Delegation: set ENABLE_PREFIX_DELEGATION=true on the aws-node DaemonSet." : ""
    }${res.customNetworking ? "\n    # Custom Networking: pods use the secondary-CIDR subnets via ENIConfig." : ""}
    maxPods: ${res.limit.limit}
  metadataOptions:
    httpTokens: required
    httpPutResponseHopLimit: 1
  tags:
    karpenter.sh/discovery: "${cluster}"
`;
}

export function eniConfigYaml(res) {
  const sec = res.cidr?.secondary;
  if (!sec || sec.error) return "";
  const docs = res.zones.map(
    (zone, i) => `apiVersion: crd.k8s.amazonaws.com/v1alpha1
kind: ENIConfig
metadata:
  name: ${zone}
spec:
  subnet: subnet-REPLACE_ME # aws_subnet.pods[${i}].id (${sec.subnets[i]})
  securityGroups:
    - sg-REPLACE_ME # EKS cluster security group`
  );
  return `# ${HEADER}
# VPC CNI Custom Networking: one ENIConfig per AZ, named after the zone.
# On the aws-node DaemonSet set:
#   AWS_VPC_K8S_CNI_CUSTOM_NETWORK_CFG=true
#   ENI_CONFIG_LABEL_DEF=topology.kubernetes.io/zone
${docs.join("\n---\n")}
`;
}

export function awsTerraform(res, { clusterName }) {
  const cluster = safeName(clusterName);
  const cidr = res.cidr;
  const sec = res.secondaryRequired && cidr?.secondary && !cidr.secondary.error ? cidr.secondary : null;
  const podLocals = sec ? `\n  pod_subnets     = ${list(sec.subnets)}` : "";

  const secondaryBlock = sec
    ? `
# Secondary CIDR for pods (VPC CNI Custom Networking).
resource "aws_vpc_ipv4_cidr_block_association" "pods" {
  vpc_id     = aws_vpc.main.id
  cidr_block = "${sec.block.cidr}"
}

resource "aws_subnet" "pods" {
  count             = length(local.azs)
  vpc_id            = aws_vpc_ipv4_cidr_block_association.pods.vpc_id
  cidr_block        = local.pod_subnets[count.index]
  availability_zone = local.azs[count.index]

  tags = {
    Name = "\${local.cluster_name}-pods-\${local.azs[count.index]}"
  }
}
`
    : "";

  const secondaryOutput = sec
    ? `
output "pod_subnet_ids" {
  value = aws_subnet.pods[*].id
}
`
    : "";

  return `# ${HEADER}
# Private subnets only; add public subnets / NAT gateways to match your egress design.
terraform {
  required_providers {
    aws = {
      source  = "hashicorp/aws"
      version = "~> 5.0"
    }
  }
}

provider "aws" {
  region = "${AWS_REGION}"
}

locals {
  cluster_name    = "${cluster}"
  azs             = ${list(res.zones)}
  private_subnets = ${list(cidr.primary.subnets)}${podLocals}
}

resource "aws_vpc" "main" {
  cidr_block           = "${cidr.vpc.cidr}"
  enable_dns_support   = true
  enable_dns_hostnames = true

  tags = {
    Name = "\${local.cluster_name}-vpc"
  }
}

resource "aws_subnet" "private" {
  count             = length(local.azs)
  vpc_id            = aws_vpc.main.id
  cidr_block        = local.private_subnets[count.index]
  availability_zone = local.azs[count.index]

  tags = {
    Name                              = "\${local.cluster_name}-private-\${local.azs[count.index]}"
    "kubernetes.io/role/internal-elb" = "1"
    "karpenter.sh/discovery"          = local.cluster_name
  }
}
${secondaryBlock}
output "vpc_id" {
  value = aws_vpc.main.id
}

output "private_subnet_ids" {
  value = aws_subnet.private[*].id
}
${secondaryOutput}`;
}

