import { AWS_REGION, GCP_REGION } from "./k8sSizing.js";

const HEADER = "Generated by the Kubernetes Sizing & CIDR Calculator. Review before applying.";

export function safeName(name, fallback = "my-cluster") {
  const cleaned = String(name || "")
    .toLowerCase()
    .replace(/[^a-z0-9-]/g, "-")
    .replace(/-+/g, "-")
    .replace(/^-|-$/g, "")
    .slice(0, 40);
  return /^[a-z]/.test(cleaned) ? cleaned : fallback;
}

const list = (items) => `[${items.map((i) => JSON.stringify(i)).join(", ")}]`;

function capacityTypes(spotRatioPct) {
  if (spotRatioPct >= 100) return ["spot"];
  if (spotRatioPct <= 0) return ["on-demand"];
  return ["spot", "on-demand"];
}

