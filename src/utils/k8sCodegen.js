function gkeNodePool({ resName, poolName, machine, spot, maxPods, min, max }) {
  return `
resource "google_container_node_pool" "${resName}" {
  name              = "${poolName}"
  cluster           = google_container_cluster.primary.id
  location          = google_container_cluster.primary.location
  node_locations    = local.zones
  max_pods_per_node = ${maxPods}

  autoscaling {
    total_min_node_count = ${min}
    total_max_node_count = ${max}
    location_policy      = "${spot ? "ANY" : "BALANCED"}"
  }

  upgrade_settings {
    max_surge       = 1
    max_unavailable = 0
  }

  node_config {
    machine_type = "${machine.type}"
    spot         = ${spot}
    disk_size_gb = 100
    oauth_scopes = ["https://www.googleapis.com/auth/cloud-platform"]

    workload_metadata_config {
      mode = "GKE_METADATA"
    }
  }
}
`;
}

export function gcpTerraform(res, { clusterName, spotRatioPct }) {
  const cluster = safeName(clusterName);
  const m = res.machine;
  const total = res.nodes.withSurge;
  const steady = res.nodes.steady;
  const ratio = Math.min(Math.max(spotRatioPct, 0), 100) / 100;
  const spotMax = res.cost.spotNodes;
  const odMax = res.cost.odNodes;
  const spotMin = Math.min(spotMax, Math.round(steady * ratio));
  const odMin = Math.min(odMax, steady - Math.round(steady * ratio));

  const pools = [];
  if (odMax > 0) {
    pools.push(
      gkeNodePool({ resName: "on_demand", poolName: `${m.family}-on-demand`, machine: m, spot: false, maxPods: res.limit.limit, min: Math.max(0, odMin), max: odMax })
    );
  }
  if (spotMax > 0) {
    pools.push(
      gkeNodePool({ resName: "spot", poolName: `${m.family}-spot`, machine: m, spot: true, maxPods: res.limit.limit, min: Math.max(0, spotMin), max: spotMax })
    );
  }

  return `# ${HEADER}
# ${m.type}: ${res.pods.effective} effective pods/node, max-pods-per-node ${res.limit.limit}
# (Pod block /${res.block.prefix} = ${res.block.ips} IPs per node). Planned: ${steady} steady, ${total} with surge.
terraform {
  required_providers {
    google = {
      source  = "hashicorp/google"
      version = "~> 6.0"
    }
  }
}

variable "project_id" {
  type = string
}

provider "google" {
  project = var.project_id
  region  = "${GCP_REGION}"
}

locals {
  cluster_name = "${cluster}"
  region       = "${GCP_REGION}"
  zones        = ${list(res.zones)}
}

resource "google_compute_network" "vpc" {
  name                    = "\${local.cluster_name}-vpc"
  auto_create_subnetworks = false
}

resource "google_compute_subnetwork" "nodes" {
  name                     = "\${local.cluster_name}-nodes"
  region                   = local.region
  network                  = google_compute_network.vpc.id
  ip_cidr_range            = "${res.primary.cidr}" # Primary range: nodes
  private_ip_google_access = true

  secondary_ip_range {
    range_name    = "pods"
    ip_cidr_range = "${res.podRange.cidr}" # up to ${res.podRange.maxNodes} nodes
  }

  secondary_ip_range {
    range_name    = "services"
    ip_cidr_range = "${res.servicesRange.cidr}"
  }
}

resource "google_container_cluster" "primary" {
  name                = local.cluster_name
  location            = local.region
  node_locations      = local.zones
  network             = google_compute_network.vpc.id
  subnetwork          = google_compute_subnetwork.nodes.id
  networking_mode     = "VPC_NATIVE"
  deletion_protection = true

  # Node pools are managed separately below.
  remove_default_node_pool  = true
  initial_node_count        = 1
  default_max_pods_per_node = ${res.limit.limit}

  ip_allocation_policy {
    cluster_secondary_range_name  = "pods"
    services_secondary_range_name = "services"
  }

  # Private cluster: the control plane /28 must not overlap any range above.
  private_cluster_config {
    enable_private_nodes    = true
    enable_private_endpoint = false
    master_ipv4_cidr_block  = "${res.master || "172.16.0.0/28"}"
  }

  workload_identity_config {
    workload_pool = "\${var.project_id}.svc.id.goog"
  }
}
${pools.join("")}`;
}
